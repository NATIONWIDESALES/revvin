// @vitest-environment node
import { PGlite } from "@electric-sql/pglite";
import { beforeAll, afterAll, describe, expect, it } from "vitest";
import { checkSlug } from "@/lib/slugRules";
import { migrationFunctions } from "./helpers/migrationFunctions";

const cases: [string, string | null][] = [
  ...["patriot-plumbing", "patriot-painting", "pilot-plumbing", "hot-pressure-washing",
    "trevino-roofing", "billings-roofing", "accountable-roofing", "secure-home-alarms",
    "security-pros", "pinstripe-painting", "verified-electric", "rewinter-roofing",
    "s3cur3-home-alarms", "billing-roofing", "otp-plumbing", "2fa-roofing"].map(slug => [slug, null] as [string, null]),
  ...["revvin", "rewvin", "revvn", "revvinn", "my-revvin-roofing", "r3vv1n-roofing",
    "revin", "rewin", "revin-roofing", "rewin-roofing", "r3v1n-roofing", "official",
    "verify", "verification", "verified", "secure", "security", "account", "billing",
    "payment", "payments", "password", "refund", "invoice", "stripe", "paypal", "wallet",
    "login", "signin", "2fa", "otp", "secure-billing", "revvin-secure", "account-verify",
    "login-otp", "s3cur3-b1ll1ng", "otp-otp", "8illing-payment", "billin9-payment"].map(slug => [slug, "reserved"] as [string, string]),
  ["fuck-roofing", "profanity"], ["my--roofing", "format"], ["12345", "numeric"],
];

describe("current server/client slug parity", () => {
  let db: PGlite;
  beforeAll(async () => {
    db = new PGlite();
    const functions = migrationFunctions();
    for (const name of ["fn_slug_reserved_words", "fn_slug_blocked_terms", "fn_slug_profanity", "fn_slug_rejection"]) {
      const sql = functions.get(name);
      if (!sql) throw new Error(`Missing ${name}`);
      await db.exec(sql);
    }
  }, 30000);
  afterAll(async () => { await db.close(); });
  it.each(cases)("validates %s consistently", async (slug, reason) => {
    const { rows } = await db.query<{ reason: string | null }>("SELECT fn_slug_rejection($1) reason", [slug]);
    expect(rows[0].reason).toBe(reason);
    expect(checkSlug(slug).reason ?? null).toBe(reason);
  });
  it("accepts 10,000 smoke suffixes generated by the current function expression", async () => {
    const definition = migrationFunctions().get("fn_smoke_customer_journey") ?? "";
    const expression = definition.match(/short text := (.*);/)?.[1];
    if (!expression) throw new Error("Missing smoke suffix generator");
    const { rows } = await db.query<{ rejected: number }>(`SELECT count(*)::int rejected FROM
      (SELECT 'smoke-' || ${expression} slug FROM
        (SELECT gen_random_uuid() uid FROM generate_series(1,10000)) inputs) candidates
      WHERE fn_slug_rejection(slug) IS NOT NULL`);
    expect(rows[0].rejected).toBe(0);
  }, 30000);
});